import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
import os

# Professional styling
sns.set_theme(style="whitegrid", font_scale=1.15)
plt.rcParams["figure.figsize"] = (10,6)
plt.rcParams["axes.titleweight"] = "bold"
plt.rcParams["axes.labelsize"] = 12
plt.rcParams["legend.fontsize"] = 11

# Confirm file exists
os.listdir()
# Load dataset
df = pd.read_csv("flood.csv")
df.head()

df.info()
df.describe()

print("Columns in dataset:")
for col in df.columns:
    print(col)

# Select all numeric columns automatically
numeric_df = df.select_dtypes(include=["number"])

# Compute summary statistics
summary_table = numeric_df.describe()

summary_table

numeric_df.head()

plt.figure()
plt.plot(numeric_df.iloc[:, 0], linewidth=2)
plt.title("Trend of Primary Numeric Variable")
plt.xlabel("Observation Index")
plt.ylabel(numeric_df.columns[0])
plt.tight_layout()
plt.savefig("plot1_trend.png", dpi=300)
plt.show()

plt.figure()
sns.scatterplot(
    x=numeric_df.iloc[:, 0],
    y=numeric_df.iloc[:, 1],
    alpha=0.7
)
plt.title("Relationship Between Two Key Variables")
plt.xlabel(numeric_df.columns[0])
plt.ylabel(numeric_df.columns[1])
plt.tight_layout()
plt.savefig("plot2_scatter.png", dpi=300)
plt.show()

plt.figure()
sns.histplot(numeric_df.iloc[:, 0], bins=30, kde=True)
plt.title("Distribution of Primary Variable")
plt.xlabel(numeric_df.columns[0])
plt.ylabel("Frequency")
plt.tight_layout()
plt.savefig("plot3_distribution.png", dpi=300)
plt.show()

plt.figure(figsize=(14, 6))

sns.boxplot(data=numeric_df)

plt.title("Comparison of Numeric Variables", fontsize=14, weight="bold")
plt.xticks(rotation=45, ha="right", fontsize=9)
plt.tight_layout()
plt.savefig("plot4_boxplot_rotated.png", dpi=300)
plt.show()